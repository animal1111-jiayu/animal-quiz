/* ============================================================
 * 计分
 * ============================================================ */
AQ.score = function (answers) {
  var raw = { ext: 0, show: 0, direct: 0, abstract: 0 };
  var tally = { ext: [], show: [], direct: [], abstract: [] };

  for (var i = 0; i < answers.length; i++) {
    var a = answers[i];
    raw[a.dim] += a.v;
    tally[a.dim].push(a.v);
  }

  var scores = {}, purity = {};
  AQ.DIM_ORDER.forEach(function (d) {
    scores[d] = Math.round((raw[d] + 16) / 32 * 100);
    var list = tally[d], same = 0;
    if (raw[d] === 0) {
      same = list.length / 2;
    } else {
      var sgn = raw[d] > 0 ? 1 : -1;
      for (var j = 0; j < list.length; j++) {
        if (list[j] !== 0 && (list[j] > 0 ? 1 : -1) === sgn) same++;
      }
    }
    purity[d] = Math.round(same / list.length * 100);
  });

  return { scores: scores, purity: purity, raw: raw };
};

/* 四维组合 */
AQ.codeOf = function (scores) {
  return (scores.ext >= 50 ? AQ.DIMS.ext.hi : AQ.DIMS.ext.lo) + '·' +
         (scores.show >= 50 ? AQ.DIMS.show.hi : AQ.DIMS.show.lo) + '·' +
         (scores.direct >= 50 ? AQ.DIMS.direct.hi : AQ.DIMS.direct.lo) + '·' +
         (scores.abstract >= 50 ? AQ.DIMS.abstract.hi : AQ.DIMS.abstract.lo);
};

AQ.dist = function (scores, vec) {
  var s = 0;
  for (var i = 0; i < AQ.DIM_ORDER.length; i++) {
    var d = AQ.DIM_ORDER[i];
    s += Math.pow(scores[d] - vec[d], 2);
  }
  return Math.sqrt(s);
};

/* 匹配：四字组合一一对应；理论上 16 格都有主，兜底用最近邻 */
AQ.match = function (scores) {
  var code = AQ.codeOf(scores);
  var animal = null;

  for (var i = 0; i < AQ.ANIMALS.length; i++) {
    if (AQ.ANIMALS[i].code === code) { animal = AQ.ANIMALS[i]; break; }
  }

  if (!animal) {
    var bd = Infinity;
    AQ.ANIMALS.forEach(function (a) {
      var d = AQ.dist(scores, a.vec);
      if (d < bd) { bd = d; animal = a; }
    });
  }

  var fit = Math.max(0, 100 - AQ.dist(scores, animal.vec) / 2);

  return {
    code: code,
    animal: animal,
    fit: fit,
    exact: true
  };
};

AQ.displayFit = function (fit) {
  return Math.max(61, Math.min(97, Math.round(fit)));
};

/* ---------------- 结果链接编解码 ---------------- */
AQ.encodeResult = function (scores) {
  return 'r=' + AQ.CONFIG.version + '.' +
    [scores.ext, scores.show, scores.direct, scores.abstract].join('.');
};

AQ.decodeResult = function (hash) {
  try {
    var m = /(?:^#?.*?)?r=(\d+)\.(\d+)\.(\d+)\.(\d+)\.(\d+)/.exec(hash || '');
    if (!m) return null;
    if (parseInt(m[1], 10) !== AQ.CONFIG.version) return null;
    var keys = ['ext', 'show', 'direct', 'abstract'];
    var scores = {};
    for (var i = 0; i < 4; i++) {
      var v = parseInt(m[i + 2], 10);
      if (isNaN(v) || v < 0 || v > 100) return null;
      scores[keys[i]] = v;
    }
    return scores;
  } catch (e) { return null; }
};

